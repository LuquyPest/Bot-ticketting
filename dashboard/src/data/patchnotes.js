// 'v2.16' < 'v2.17' < 'v2.17.1'
export function compareVersions(a, b) {
  const pa = String(a).slice(1).split('.').map(Number), pb = String(b).slice(1).split('.').map(Number);
  for (let k = 0; k < Math.max(pa.length, pb.length); k++) if ((pa[k] || 0) !== (pb[k] || 0)) return (pa[k] || 0) - (pb[k] || 0);
  return 0;
}
